export type DictKey = keyof typeof ru;
export const t = (l: Locale, k: DictKey, vars?: Record<string, string | number>) => {
  let s = dict[l][k];
  if (vars) for (const [a, b] of Object.entries(vars)) s = s.replace(`{${a}}`, String(b));
  return s;
};

